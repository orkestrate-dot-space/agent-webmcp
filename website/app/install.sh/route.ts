// GET /install.sh — the one-line installer. Plain text shell script:
//   curl -fsSL agent-webmcp.vercel.app/install.sh | bash
// Interactive when stdout is a TTY (asks, reads /dev/tty); piped or
// agent-driven runs take env defaults (AGENT_WEBMCP_BROWSER,
// AGENT_WEBMCP_DIR). set -euo pipefail: any
// failed step aborts the install.
const LINES = [
  "#!/usr/bin/env bash",
  "# agent-webmcp installer — source builds only until release binaries exist.",
  "set -euo pipefail",
  "",
  'REPO="https://github.com/system1970/agent-webmcp"',
  'DEST="${AGENT_WEBMCP_DIR:-$HOME/agent-webmcp}"',
  'BIN_DIR="$HOME/.local/bin"',
  'MODE="${AGENT_WEBMCP_BROWSER:-}"',
  "",
  "# Piped (curl|bash) keeps stdin as the script — prompts go to the",
  "# terminal, answers come from /dev/tty. Agents/CI get env defaults.",
  'INTERACTIVE=0',
  'if [ -t 1 ] && [ -e /dev/tty ]; then INTERACTIVE=1; fi',
  "ask() {",
  '  _var="$1"; _prompt="$2"; _def="$3"; _ans=""',
  '  if [ "$INTERACTIVE" = 1 ]; then',
  '    printf "%s [%s]: " "$_prompt" "$_def" > /dev/tty',
  '    read -r _ans < /dev/tty || _ans=""',
  '    if [ -z "$_ans" ]; then _ans="$_def"; fi',
  "  else",
  '    _ans="$_def"',
  "  fi",
  '  printf -v "$_var" "%s" "$_ans"',
  "}",
  "reachable() {",
  '  curl -sf --max-time 2 "$1/json/version" > /dev/null 2>&1',
  "}",
  "# First reachable local browser: agent-browser daemon tmp ports,",
  "# then loopback 9222/9229 (an open debug port is the opt-in).",
  "detect_browser() {",
  '  for d in "${TMPDIR:-/tmp}"/agent-browser-chrome-*/DevToolsActivePort; do',
  '    [ -f "$d" ] || continue',
  '    p="$(head -n 1 "$d" 2>/dev/null | tr -d " \\t\\r\\n")"',
  '    case "$p" in ""|*[!0-9]*) continue;; esac',
  '    if reachable "http://127.0.0.1:$p"; then echo "http://127.0.0.1:$p"; return 0; fi',
  "  done",
  '  for p in 9222 9229; do',
  '    if reachable "http://127.0.0.1:$p"; then echo "http://127.0.0.1:$p"; return 0; fi',
  "  done",
  '  return 1',
  "}",
  "",
  'echo "== 1/4 machine =="',
  'command -v git >/dev/null || { echo "need git first"; exit 1; }',
  'command -v bun >/dev/null || { echo "need bun first (https://bun.sh)"; exit 1; }',
  'command -v curl >/dev/null || { echo "need curl first"; exit 1; }',
  "",
  'if ! command -v agent-browser >/dev/null; then',
  '  echo "installing agent-browser (the browser backend)..."',
  '  if command -v npm >/dev/null; then npm i -g agent-browser',
  '  elif command -v brew >/dev/null; then brew install agent-browser',
  '  elif command -v cargo >/dev/null; then cargo install agent-browser',
  '  else echo "no npm/brew/cargo — install agent-browser manually: https://agent-browser.dev/installation"; fi',
  "fi",
  'if command -v agent-browser >/dev/null; then',
  '  if [ "$(uname)" = "Linux" ]; then',
  '    agent-browser install --with-deps || agent-browser install || echo "warning: agent-browser Chrome download failed — open will fail until a CDP browser is reachable."',
  "  else",
  '    agent-browser install || echo "warning: agent-browser Chrome download failed — open will fail until a CDP browser is reachable."',
  "  fi",
  "fi",
  "",
  'echo "== 2/4 engine =="',
  'if [ -d "$DEST/.git" ]; then',
  '  # Our own bun install churns bun.lock — restore it, then refuse',
  '  # on anything else (same rule as upgrade: never overwrite work).',
  '  git -C "$DEST" checkout -- bun.lock 2>/dev/null || true',
  '  if [ -n "$(git -C "$DEST" status --porcelain)" ]; then',
  '    echo "DEST $DEST has local changes:"; git -C "$DEST" status --porcelain;',
  '    echo "stash, commit, or rm -rf it and re-run."; exit 1;',
  "  fi",
  '  git -C "$DEST" pull --ff-only',
  "else",
  '  git clone "$REPO" "$DEST"',
  "fi",
  'cd "$DEST"',
  "bun install",
  "bun run gate",
  "bun run compile",
  'mkdir -p "$BIN_DIR"',
  "# atomic replace (cp fails on a running binary — rename wins)",
  'cp dist/agent-webmcp "$BIN_DIR/agent-webmcp.new"',
  'mv "$BIN_DIR/agent-webmcp.new" "$BIN_DIR/agent-webmcp"',
  'BIN="$BIN_DIR/agent-webmcp"',
  '"$BIN" --version',
  "",
  'echo "== 3/4 browser =="',
  '# The engine keeps no endpoint: the driver feeds it per open call.',
  '# Nothing is persisted here — discovery handles the rest.',
  'if [ -n "$MODE" ]; then :',
  'elif [ -n "$FOUND" ]; then echo "found a reachable browser at $FOUND."; MODE="auto"',
  'elif [ "$INTERACTIVE" = 1 ]; then',
  '  echo "no browser answering. Pick one:" > /dev/tty',
  '  echo "  [1] agent-managed (default — boot the agent-browser daemon)" > /dev/tty',
  '  echo "  [2] my own Chrome (you start it with --remote-debugging-port=9222)" > /dev/tty',
  '  echo "  [3] remote CDP URL (used for the verify step only, never stored)" > /dev/tty',
  '  ask MODE "choice" "1"',
  '  case "$MODE" in 1) MODE="agent";; 2) MODE="chrome";; 3) MODE="url-ask";; agent|chrome) :;; *) MODE="url";; esac',
  "else",
  '  MODE="agent"',
  "fi",
  'CDP=""',
  'case "$MODE" in',
  "  auto) :;;",
  '  agent) agent-browser open about:blank > /dev/null 2>&1 || true;;',
  "  chrome)",
  '    echo "run, then return here:"',
  '    echo "  google-chrome --remote-debugging-port=9222 --user-data-dir=\"$HOME/.chrome-debug\""',
  '    tries=60; [ "$INTERACTIVE" = 1 ] || tries=5',
  '    i=0; while ! reachable http://127.0.0.1:9222; do',
  '      i=$((i + 1)); if [ "$i" -ge "$tries" ]; then echo "9222 never answered — pass AGENT_WEBMCP_BROWSER=<URL> or start Chrome and re-run."; exit 1; fi',
  "      sleep 1",
  "    done;;",
  '  url-ask) printf "CDP URL (verify only, never stored): " > /dev/tty; read -r CDP < /dev/tty || CDP=""; [ -n "$CDP" ] || { echo "empty URL — aborting."; exit 1; };;',
  '  *) CDP="$MODE";;',
  "esac",
  'if [ -n "$CDP" ]; then',
  '  reachable "$CDP" || echo "warning: $CDP does not answer yet — continuing, open will fail loud until it does."',
  "fi",
  "",
  'echo "== 4/4 verify =="',
  '"$BIN" doctor',
  'EP_MJS="${TMPDIR:-/tmp}/agent-webmcp-print-ep.mjs"',
  'cat > "$EP_MJS" <<\"MJS\"',
  "const t = await new Response(Bun.stdin.stream()).text();",
  "const d = JSON.parse(t);",
  "console.log(d.browser && d.browser.reachable ? d.browser.endpoint : \"none\");",
  "MJS",
  'EP="$("$BIN" doctor 2>/dev/null | bun "$EP_MJS")"',
  'if [ "$EP" = "none" ] && [ -n "$FOUND" ]; then EP="$FOUND"; fi',
  'rm -f "$EP_MJS"',
  'H_MJS="${TMPDIR:-/tmp}/agent-webmcp-print-handle.mjs"',
  'cat > "$H_MJS" <<\"MJS\"',
  "const t = await new Response(Bun.stdin.stream()).text();",
  "console.log(JSON.parse(t).handle);",
  "MJS",
  'if [ -n "$CDP" ]; then OPEN_FLAGS="--cdp $CDP"; else OPEN_FLAGS=""; fi',
  'H="$("$BIN" open $OPEN_FLAGS --json https://example.com | bun "$H_MJS")"',
  'rm -f "$H_MJS"',
  '"$BIN" close "$H" --yes',
  'echo "installed to $BIN_DIR/agent-webmcp — ensure $BIN_DIR is on your PATH."',
  'echo "browser: $EP — open connects here (per-call cdp, then daemon, then 9222/9229)."',
  "",
];

export async function GET(): Promise<Response> {
  return new Response(`${LINES.join("\n")}`, {
    headers: { "Content-Type": "text/plain; charset=utf-8" },
  });
}
